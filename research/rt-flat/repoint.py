"""Stage 2 of the flip: every caller of `BeamLisp.RT` names `BeamLisp.Ns.Rt`.

Run ONLY after stage 1 has produced a boot tier whose `Ns.Rt` beam exists
(`build/Elixir.BeamLisp.Ns.Rt.beam`): the Elixir half is compiled before any
`.bl` loads, and a caller of a module that does not exist yet cannot boot.

Rewrites, per file kind:
  .ex / .exs   `BeamLisp.RT.f(`   → `BeamLisp.Ns.Rt.f(`
               `alias BeamLisp.{…, RT, …}` + bare `RT.f(` → the same, via
               `alias BeamLisp.Ns.Rt, as: RT` so call sites keep reading `RT.`
  .bl / .md    `BeamLisp.RT/f`    → `BeamLisp.Ns.Rt/f`
               `Elixir.BeamLisp.RT` (a module atom) → `Elixir.BeamLisp.Ns.Rt`

Not touched: lib/beam_lisp/rt.ex (deleted), test/fixtures (regenerated by their
own test), priv/bootstrap (regenerated by `bl seed`), prose that names the old
module as history (comments are rewritten too — the module no longer exists, a
comment naming it would describe code that is not there).
"""
import re
import subprocess
import sys

EXCLUDE = (':!lib/beam_lisp/rt.ex', ':!test/fixtures', ':!priv/bootstrap',
           ':!research', ':!!tasks', ':!.local')

files = subprocess.run(
    ['git', 'grep', '-l', '-E', r'BeamLisp\.RT\b|alias BeamLisp\.\{[^}]*\bRT\b', '--',
     'lib', 'priv', 'test', 'bin', 'scripts', *EXCLUDE],
    capture_output=True, text=True).stdout.split()

changed = 0
for f in files:
    s = open(f, encoding='utf-8').read()
    o = s
    if f.endswith(('.ex', '.exs')):
        s = re.sub(r'\bBeamLisp\.RT\b(?!\w)', 'BeamLisp.Ns.Rt', s)
        # alias BeamLisp.{A, RT, B} → alias BeamLisp.{A, B} + alias BeamLisp.Ns.Rt, as: RT
        def fix_alias(m):
            names = [n.strip() for n in m.group(2).split(',')]
            rest = [n for n in names if n != 'RT']
            line = f'{m.group(1)}alias BeamLisp.{{{", ".join(rest)}}}' if len(rest) > 1 else \
                   (f'{m.group(1)}alias BeamLisp.{rest[0]}' if rest else '')
            extra = f'{m.group(1)}alias BeamLisp.Ns.Rt, as: RT'
            return (line + '\n' + extra) if line else extra
        s = re.sub(r'^([ \t]*)alias BeamLisp\.\{([^}]*\bRT\b[^}]*)\}', fix_alias, s, flags=re.M)
    else:
        s = re.sub(r'\bElixir\.BeamLisp\.RT\b(?![\w.])', 'Elixir.BeamLisp.Ns.Rt', s)
        s = re.sub(r'\bBeamLisp\.RT/', 'BeamLisp.Ns.Rt/', s)
        s = re.sub(r'\bBeamLisp\.RT\b(?![\w./])', 'BeamLisp.Ns.Rt', s)
    if s != o:
        open(f, 'w', encoding='utf-8').write(s)
        changed += 1
print(f'files rewritten: {changed} of {len(files)}')
if '--check' in sys.argv:
    left = subprocess.run(['git', 'grep', '-n', '-E', r'BeamLisp\.RT\b', '--',
                           'lib', 'priv', 'test', 'bin', *EXCLUDE],
                          capture_output=True, text=True).stdout
    print(left or 'no BeamLisp.RT left')
